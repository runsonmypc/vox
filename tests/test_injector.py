def test_pastes_are_serialized_across_threads(monkeypatch):
    """A paste still finishing in a cancelled worker thread must restore before the next one starts."""
    inside = threading.Event()
    release = threading.Event()
    order = []

    def slow_paste(text, app_type):
        order.append(f"start {text}")
        if text == "first":
            inside.set()
            release.wait(5)
        order.append(f"end {text}")

    monkeypatch.setattr(injector, "_paste_macos", slow_paste)
    monkeypatch.setattr(injector, "_paste_linux", slow_paste)

    first = threading.Thread(target=injector.paste, args=("first",))
    first.start()
    assert inside.wait(5)
    second = threading.Thread(target=injector.paste, args=("second",))
    second.start()
    time.sleep(0.05)
    assert order == ["start first"]
    release.set()
    first.join(5)
    second.join(5)
    assert order == ["start first", "end first", "start second", "end second"]


