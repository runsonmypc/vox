class FakeOwnerProcess:
    """A stand-in for the foreground `xclip -quiet` that owns CLIPBOARD during the paste."""

    def __init__(self, fail: bool = False) -> None:
        read_fd, self._write_fd = os.pipe()
        self.stderr = os.fdopen(read_fd, "rb", buffering=0)
        self.stdin = SimpleNamespace(data=b"", write=self._stdin_write, close=lambda: None)
        self.returncode = None
        self.served = 0
        self.terminated = False
        if fail:
            self._say(b"Error: Can't open display: (null)\n")
            self._exit(1)
        else:
            self._say(b"  Waiting for selection request number 1\n")

    def _stdin_write(self, data: bytes) -> None:
        self.stdin.data += data

    def _say(self, line: bytes) -> None:
        if self._write_fd is not None:
            os.write(self._write_fd, line)

    def _exit(self, code: int) -> None:
        if self.returncode is None:
            self.returncode = code
        if self._write_fd is not None:
            os.close(self._write_fd)
            self._write_fd = None

    def serve(self, count: int = 1) -> None:
        for _ in range(count):
            self.served += 1
            self._say(f"  Waiting for selection request number {self.served + 1}\n".encode())

    def lose_selection(self) -> None:
        """Another client took CLIPBOARD: xclip exits."""
        self._exit(0)

    def poll(self):
        return self.returncode

    def terminate(self) -> None:
        self.terminated = True
        self._exit(-15)

    def kill(self) -> None:
        self._exit(-9)

    def wait(self, timeout=None):
        return self.returncode


class FakeX11:
    """Fake xclip/xdotool: a CLIPBOARD owner offering `clipboard` (target -> bytes), or nothing."""

    def __init__(self, clipboard: dict[str, bytes] | None = None, owner_fails: bool = False) -> None:
        self.clipboard = clipboard
        self.owner_fails = owner_fails
        self.owner: FakeOwnerProcess | None = None
        self.read_error: Exception | None = None
        self.keys_error: Exception | None = None
        self.writes: list[tuple[str | None, bytes]] = []
        self.events: list[str] = []
        self.on_paste = lambda: self.owner.serve(2)  # TARGETS, then the text
        self.xtest = MagicMock(side_effect=self._paste)

    def _paste(self) -> None:
        self.events.append("paste")
        self.on_paste()

    def popen(self, args, **kwargs):
        assert args == ["xclip", "-quiet", "-selection", "clipboard"]
        self.owner = FakeOwnerProcess(fail=self.owner_fails)
        return self.owner

    def run(self, args, **kwargs):
        assert kwargs.get("timeout"), f"{args[0]} runs without a timeout"
        assert not kwargs.get("shell")
        if args[0] == "xdotool":
            self.events.append(f"keys {args[-1]}")
            if self.keys_error is not None:
                raise self.keys_error
            self._paste()
            return subprocess.CompletedProcess(args, 0)
        assert args[:3] == ["xclip", "-selection", "clipboard"]
        target = args[args.index("-t") + 1] if "-t" in args else None
        if "-o" in args:
            if self.read_error is not None:
                raise self.read_error
            if self.clipboard is None or (target != "TARGETS" and target not in self.clipboard):
                raise subprocess.CalledProcessError(1, args)
            data = b"TARGETS\n" + b"".join(t.encode() + b"\n" for t in self.clipboard) if target == "TARGETS" else self.clipboard[target]
            return subprocess.CompletedProcess(args, 0, stdout=data, stderr=b"")
        # A write: the new background xclip takes the selection from the paste's owner
        assert kwargs.get("stdout") == subprocess.DEVNULL and kwargs.get("stderr") == subprocess.DEVNULL
        self.events.append("restore")
        self.writes.append((target, kwargs["input"]))
        if self.owner is not None:
            self.owner.lose_selection()
        return subprocess.CompletedProcess(args, 0)


