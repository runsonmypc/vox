def _items(pb) -> list[dict[str, bytes]]:
    return [{t: bytes(item.dataForType_(t)) for t in item.types()} for item in pb.pasteboardItems() or ()]


def _write_items(pb, *items: dict[str, bytes]) -> None:
    import AppKit
    from Foundation import NSData

    objects = []
    for types in items:
        item = AppKit.NSPasteboardItem.alloc().init()
        for pasteboard_type, data in types.items():
            item.setData_forType_(NSData.dataWithBytes_length_(data, len(data)), pasteboard_type)
        objects.append(item)
    pb.clearContents()
    assert pb.writeObjects_(objects)


