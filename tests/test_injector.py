def test_clipboard_owner_counts_requests_split_across_reads(monkeypatch):
    """xclip's progress lines can arrive in pieces; the count must still be right."""
    process = FakeOwnerProcess()
    monkeypatch.setattr(injector.subprocess, "Popen", lambda *a, **k: process)
    owner = injector._ClipboardOwner(b"text")
    assert owner.wait_served(0, 1)
    assert owner.served == 0

    process._say(b"  Waiting for selection req")
    assert not owner.wait_served(1, 0.05)
    process._say(b"uest number 2\n  Waiting for selection request number 3\n")
    assert owner.wait_served(2, 1)
    assert owner.served == 2

    process.lose_selection()
    assert not owner.wait_served(3, 1)
    assert owner.exited()
    owner.close()
